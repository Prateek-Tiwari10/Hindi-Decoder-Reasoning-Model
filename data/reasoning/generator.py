"""Synthetic transitive/ordering reasoning dataset generator (Phase 3, Part 1).

WHAT THIS MODULE IS
-------------------
The generator for the Hindi reasoning corpus.  Every language string lives in
``configs/hi*.yaml`` and this file contains none, so the logic and the surface
text stay separate.

Importing this module has no side effects.  ``run.py`` is the entry point.

THE CENTRAL DESIGN DECISION: GROUND TRUTH IS CONSTRUCTED, NEVER INFERRED
------------------------------------------------------------------------
Every problem starts from a uniformly random permutation of the sampled names.
That permutation *is* the truth.  Premises are then emitted to be consistent
with it, and the answer is read off the permutation rather than solved for.
A generator that instead emitted premises and then solved them would be one
bug away from silently mislabelling part of the corpus.

Because the premises are emitted from the truth, the uniqueness gate
(:func:`uniquely_determines_total_order`) should never fire.  It is run on
every single problem anyway: it is cheap at n <= 7, and a gate that never
fires is the evidence that the construction is sound.

WHY RELATION-ONLY IS THE HEADLINE FAMILY
----------------------------------------
Problems state relations between entities ("A is taller than B"), not their
values.  If values were given, every question would be a lookup and a compare,
and depth 4 would be no harder than depth 3.  Stating only relations is what
makes chain depth a genuine difficulty axis -- a depth-4 chain requires one
more inference hop than a depth-3 chain, by construction.

WHY EACH RECORD CARRIES ITS OWN SEED
------------------------------------
A record is generated by an RNG seeded from ``(master seed, slice tag, index)``
alone.  Any single record can therefore be regenerated in isolation, rejection
resampling stays inside that record's own stream instead of shifting every
later record, and byte-identical output across runs (check G7) follows from
the construction rather than from luck.
"""

from __future__ import annotations

import random
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable, Sequence

import yaml

#: Marker separating the loss-masked prompt from the loss-active completion.
#: The completion begins with a single space, so ``prompt + completion`` is the
#: exact training string with no separator of its own (§3).
COMPLETION_PREFIX = " "

#: Danda.  Sentences are assembled without it and joined with it, so no
#: template has to carry punctuation that the joiner would duplicate.
DANDA = "।"

#: Short tags used in record ids.
FAMILY_ABBREV = {"relation": "rel", "numeric": "num", "mixed": "mix"}


