def weighted_choice(rng: random.Random, weights: dict[str, float]) -> str:
    """Draw one key in proportion to its weight.

    Args:
        rng: Seeded generator.
        weights: Key to non-negative weight.  Need not sum to 1.

    Returns:
        The chosen key.

    Raises:
        ValueError: If every weight is zero, which would make the draw
            undefined rather than merely unlikely.
    """
    keys = sorted(weights)
    values = [float(weights[k]) for k in keys]
    total = sum(values)
    if total <= 0:
        raise ValueError(f"all weights are zero: {weights}")
    threshold = rng.random() * total
    running = 0.0
    for key, value in zip(keys, values):
        running += value
        if threshold < running:
            return key
    return keys[-1]


def choose_question_type(rng: random.Random, family: str, depth: int,
                         build_config: dict) -> str:
    """Pick a question type valid at this depth for this family.

    Two depth-2 exclusions are structural rather than stylistic:

    * ``pairwise`` needs a queried pair that is *not* a stated premise (§6.2).
      At depth 2 the only pair in the problem is the single premise, so no
      valid pairwise question exists and the type is dropped.
    * Whatever is dropped has its probability mass renormalised across the
      remaining types rather than reassigned to a fixed default, so the
      configured ratios are preserved among the types that survive.

    Args:
        rng: Seeded generator.
        family: ``"relation"``, ``"numeric"`` or ``"mixed"``.
        depth: Number of entities in the chain.
        build_config: The build plan, for ``question_mix``.

    Returns:
        One of ``"extremum"``, ``"pairwise"``, ``"ordering"``, ``"bound"``.
    """
    mix = dict(build_config["question_mix"][family])
    if depth < 3:
        mix.pop("pairwise", None)
    return weighted_choice(rng, mix)


def sample_true_order(rng: random.Random, pool: Sequence[str],
                      depth: int) -> list[str]:
    """Draw the ground-truth total order for one problem.

    Names are sampled uniformly without replacement and then permuted
    uniformly, so a name is equally likely to land in any position.  That is
    what makes ``P(answer | name) = P(answer)`` (invariant §4) hold by
    construction rather than by post-hoc filtering.

    Args:
        rng: Seeded generator.
        pool: Names to draw from (train pool or test pool, never both).
        depth: How many entities to draw.

    Returns:
        The entities in DESCENDING order on the domain attribute; index 0 is
        the greatest.
    """
    return rng.sample(list(pool), depth)


def assign_values(rng: random.Random, depth: int, low: int,
                  high: int) -> list[int]:
    """Draw distinct integer attribute values consistent with the true order.

    Args:
        rng: Seeded generator.
        depth: How many values are needed.
        low: Inclusive lower bound of the domain's range.
        high: Inclusive upper bound.

    Returns:
        ``depth`` distinct integers sorted DESCENDING, aligned position by
        position with ``true_order``.
    """
    return sorted(rng.sample(range(low, high + 1), depth), reverse=True)


