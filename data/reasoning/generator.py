def build_completion(config: dict, domain: dict, order: Sequence[str],
                     premises: Sequence[Premise], query: dict, answer: str,
                     anchor: dict | None, genders: dict[str, str]) -> str:
    """Assemble the loss-active completion: normalise, then chain, then answer.

    The three-step shape is fixed for every family and question type (§7):

    1. every premise restated in a single ``>`` direction,
    2. the assembled total order as one terse symbolic chain,
    3. one natural sentence, then the answer cue and the canonical label.

    Step 2 is emitted even for numeric problems, where the §7 illustration
    omits it.  Keeping the shape uniform is what lets Part 3 score chain
    validity with one parser instead of one per family.

    Every completion ends with ``<answer cue> <label><danda>``.  That is the
    whole of the G8 extraction rule: the label is what sits between the LAST
    answer cue in the completion and the final danda.  The alternative -- a
    natural sentence that happens to end in the label -- does not survive
    Hindi word order, where the copula comes last.

    Args:
        config: Language config.
        domain: The chosen domain's block.
        order: The true order, greatest first.
        premises: Premises in presentation order.
        query: Query metadata from one of the question builders.
        answer: The canonical answer label.
        anchor: ``{"entity", "value", "unit"}`` for numeric and mixed
            families, or None for the relation family.
        genders: Name to gender, for adjective agreement.

    Returns:
        The completion, beginning with a single space (§3).
    """
    templates = resolve_templates(config, domain)
    connectives = config["connectives"]
    segments: list[str] = []

    if anchor is not None:
        segments.append(templates["cot_anchor"].format(
            e=anchor["entity"], v=anchor["value"], unit=anchor["unit"]))

    segments.append(", ".join(
        render_cot_premise(config, order, p) for p in premises))
    segments.append(f"{connectives['order']} {render_chain(order)}")

    kind = query["kind"]
    if kind == "extremum":
        # Here the subject IS the answer entity, so unlike the question the
        # final sentence does agree with it -- the completion is the target,
        # not the input, so there is nothing left to leak.
        adjective_form = adjective(
            domain, "more" if query["end"] == "max" else "less",
            gender_of(genders, answer))
        segments.append(templates["final_extremum"].format(
            adj=adjective_form, ans=answer))
    elif kind == "pairwise":
        # State the TRUE relation between the queried pair, which is not
        # necessarily the relation the question proposed.
        first_is_greater = order.index(query["a"]) < order.index(query["b"])
        adjective_form = adjective(
            domain, "more" if first_is_greater else "less",
            gender_of(genders, query["a"]))
        segments.append(templates["final_pairwise"].format(
            therefore=connectives["therefore"], a=query["a"], b=query["b"],
            adj=adjective_form))
    elif kind == "ordering":
        segments.append(templates["final_ordering"].format(
            therefore=connectives["therefore"]))
    elif kind == "bound":
        query_is_greater = order.index(query["entity"]) < order.index(query["anchor"])
        segments.append(templates["cot_bound"].format(
            then=connectives["then"], e=query["entity"],
            sym=">" if query_is_greater else "<", anchor=query["anchor"],
            v=query["value"], unit=query["unit"]))
        bound_word = config["bounds"]["more" if query_is_greater else "less"]
        segments.append(templates["final_bound"].format(
            therefore=connectives["therefore"], e=query["entity"],
            v=query["value"], unit=query["unit"], bound=bound_word))
    else:
        raise ValueError(f"unknown query kind {kind!r}")

    segments.append(f"{config['cues']['answer']} {answer}")
    return COMPLETION_PREFIX + join_sentences(segments)


def extract_answer(config: dict, completion: str) -> str:
    """Recover the canonical label from a completion -- the G8 rule.

    Documented here because Part 3 scores exact match with exactly this rule,
    applied to model output rather than to generated text.  Stated in full:

        take the substring after the LAST occurrence of the answer cue, strip
        whitespace, then strip one trailing danda.

    "Last" rather than "first" matters: the prompt's own answer cue is not part
    of the completion, but a future format change that repeats the cue would
    otherwise silently break extraction.

    Args:
        config: Language config, for the answer cue.
        completion: A completion string.

    Returns:
        The extracted label.

    Raises:
        ValueError: If the completion has no answer cue at all.
    """
    cue = config["cues"]["answer"]
    position = completion.rfind(cue)
    if position < 0:
        raise ValueError(f"no answer cue {cue!r} in completion: {completion!r}")
    tail = completion[position + len(cue):].strip()
    return tail[:-1].strip() if tail.endswith(DANDA) else tail


def build_prompt(config: dict, premise_sentences: Sequence[str],
                 question: str) -> str:
    """Assemble the loss-masked prompt, ending exactly at the answer cue.

    The cue terminates the prompt with no trailing space; the completion
    supplies the space instead.  That makes the mask boundary a property of the
    data rather than a convention Part 2 has to remember.

    Args:
        config: Language config.
        premise_sentences: Rendered premises, each already danda-terminated.
        question: The rendered question sentence.

    Returns:
        The prompt string.
    """
    cues = config["cues"]
    body = " ".join([*premise_sentences, question])
    return f"{cues['question']} {body}\n{cues['answer']}"


