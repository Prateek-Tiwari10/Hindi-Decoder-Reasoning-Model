@dataclass(frozen=True)
class Premise:
    """One stated comparison between two entities.

    Attributes:
        higher: Index in ``true_order`` of the greater entity.
        lower: Index in ``true_order`` of the lesser entity.
        flipped: True if the premise is *stated* as "lower is less than
            higher" rather than "higher is more than lower".  The relation is
            the same either way; only the surface polarity differs.
    """

    higher: int
    lower: int
    flipped: bool

    @property
    def consecutive(self) -> bool:
        """True if this premise links adjacent positions in the true order."""
        return self.lower == self.higher + 1


def consecutive_edges(depth: int) -> list[tuple[int, int]]:
    """The covering chain of the true order: ``(0,1), (1,2), ...``.

    Every one of these is mandatory.  See :func:`select_premise_edges`.

    Args:
        depth: Number of entities.

    Returns:
        The ``depth - 1`` consecutive edges.
    """
    return [(i, i + 1) for i in range(depth - 1)]


def nonconsecutive_pairs(depth: int) -> list[tuple[int, int]]:
    """All pairs spanning more than one position, ``(i, j)`` with ``j > i+1``.

    Args:
        depth: Number of entities.

    Returns:
        Every non-consecutive ordered pair, higher index first in the tuple
        meaning greater on the attribute.
    """
    return [(i, j) for i in range(depth) for j in range(i + 2, depth)]


def select_premise_edges(rng: random.Random, depth: int, build_config: dict,
                         reserved: tuple[int, int] | None = None
                         ) -> list[tuple[int, int]]:
    """Choose the premise set for one problem.

    ALL consecutive edges are always included, and this is forced rather than
    chosen.  The transitive reduction of a total order is exactly its chain of
    consecutive edges: for adjacent ``i`` and ``i+1`` there is no path through
    any third entity, since every other entity is either above ``i`` or below
    ``i+1``.  Drop one and that pair becomes underdetermined, and the §5.4
    uniqueness gate rejects the problem.  This is why §5.3's "replace
    consecutive edges with a spanning set of non-consecutive edges" mode is not
    implemented -- it cannot exist.

    Non-consecutive edges are therefore added as *redundant* premises.  They
    are what force the model to normalise a premise set that is larger than the
    chain, instead of reading the answer straight off a pre-sorted list.

    Args:
        rng: Seeded generator.
        depth: Number of entities.
        build_config: The build plan, for the ``nonconsecutive`` block.
        reserved: A pair that must NOT become a premise, because a pairwise
            question is going to query it and §6.2 requires the queried pair to
            be underived.

    Returns:
        The premise edges as ``(higher_index, lower_index)`` tuples.
    """
    edges = consecutive_edges(depth)
    settings = build_config["nonconsecutive"]
    if depth < settings["min_depth"]:
        return edges

    candidates = [p for p in nonconsecutive_pairs(depth) if p != reserved]
    if not candidates:
        return edges

    k = rng.randint(settings["k_min"], settings["k_max"])
    k = min(k, len(candidates))
    return edges + rng.sample(candidates, k)


def transitive_closure(depth: int,
                       edges: Iterable[tuple[int, int]]) -> list[list[bool]]:
    """Reachability matrix of the premise graph (Floyd-Warshall).

    Args:
        depth: Number of entities.
        edges: Premise edges as ``(higher, lower)``.

    Returns:
        ``reach[i][j]`` is True if the premises entail that entity ``i`` is
        greater than entity ``j``.
    """
    reach = [[False] * depth for _ in range(depth)]
    for higher, lower in edges:
        reach[higher][lower] = True
    for k in range(depth):
        for i in range(depth):
            if reach[i][k]:
                row_k = reach[k]
                row_i = reach[i]
                for j in range(depth):
                    if row_k[j]:
                        row_i[j] = True
    return reach


def uniquely_determines_total_order(depth: int,
                                    edges: Iterable[tuple[int, int]]) -> bool:
    """The uniqueness gate of §5.4.

    A problem is well-posed only if its premises pin down exactly one total
    order.  Three ways that can fail, all caught here:

    * a cycle (``reach[i][i]``) means the premises contradict each other;
    * ``reach[i][j]`` and ``reach[j][i]`` both true is the same contradiction
      seen pairwise;
    * neither true means the pair is incomparable and the order is ambiguous,
      so more than one answer would be defensible.

    Args:
        depth: Number of entities.
        edges: Premise edges.

    Returns:
        True if the transitive closure is a strict total order.
    """
    reach = transitive_closure(depth, edges)
    for i in range(depth):
        if reach[i][i]:
            return False
        for j in range(i + 1, depth):
            if reach[i][j] == reach[j][i]:
                return False
    return True


def apply_polarity(rng: random.Random, edges: Sequence[tuple[int, int]]
                   ) -> list[Premise]:
    """Shuffle premise order and flip each premise's polarity with p = 0.5.

    Scrambling stops the premises from being readable as a pre-sorted chain,
    and independent polarity flips mean the model cannot assume a fixed
    direction.  Together they are what force an actual normalisation step
    rather than surface pattern-matching (§5.5).

    Args:
        rng: Seeded generator.
        edges: Premise edges as ``(higher, lower)``.

    Returns:
        Premises in presentation order, each carrying its stated polarity.
    """
    premises = [Premise(higher=h, lower=l, flipped=rng.random() < 0.5)
                for h, l in edges]
    rng.shuffle(premises)
    return premises


