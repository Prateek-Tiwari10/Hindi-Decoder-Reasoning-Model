def render_premise(config: dict, domain: dict, order: Sequence[str],
                   premise: Premise, genders: dict[str, str]) -> str:
    """Render one premise as a sentence in the target language.

    The adjective agrees with the SUBJECT of the sentence, which swaps with the
    polarity: a directly-stated premise says "higher is more-X than lower" and
    takes the higher entity's gender, while a flipped one says "lower is less-X
    than higher" and takes the lower entity's.

    Args:
        config: Language config.
        domain: The chosen domain's block (``attr``/``more``/``less``/...).
        order: The true order, greatest first.
        premise: The premise to render, carrying its stated polarity.
        genders: Name to gender, for adjective agreement.

    Returns:
        One sentence ending in a danda.
    """
    templates = resolve_templates(config, domain)
    higher, lower = order[premise.higher], order[premise.lower]
    if premise.flipped:
        return templates["premise_less"].format(
            lo=lower, hi=higher,
            less=adjective(domain, "less", gender_of(genders, lower)))
    return templates["premise_more"].format(
        hi=higher, lo=lower,
        more=adjective(domain, "more", gender_of(genders, higher)))


def render_premise_record(order: Sequence[str], premise: Premise) -> dict:
    """Structured form of a premise, for chain-validity scoring in Part 3.

    Mirrors the *stated* polarity rather than normalising it, so the record
    says what the model was actually shown.

    Args:
        order: The true order, greatest first.
        premise: The premise.

    Returns:
        ``{"a": ..., "b": ..., "rel": ">" | "<"}`` where ``a`` is the entity
        named first in the sentence.
    """
    higher, lower = order[premise.higher], order[premise.lower]
    if premise.flipped:
        return {"a": lower, "b": higher, "rel": "<"}
    return {"a": higher, "b": lower, "rel": ">"}


def render_cot_premise(config: dict, order: Sequence[str],
                       premise: Premise) -> str:
    """Render the normalisation step for one premise.

    A directly-stated premise is echoed as ``A > B``.  A flipped one is
    restated first and then normalised -- ``B < A यानी A > B`` -- so the
    normalisation is visible in the chain of thought rather than done silently.

    Args:
        config: Language config.
        order: The true order, greatest first.
        premise: The premise.

    Returns:
        One clause, with no trailing punctuation.
    """
    # Language templates directly, not resolve_templates: this step emits the
    # purely symbolic chain (``A > B``), which carries no adjective and so is
    # identical for every domain and every gender.
    templates = config["templates"]
    higher, lower = order[premise.higher], order[premise.lower]
    if premise.flipped:
        return templates["cot_flipped"].format(
            lo=lower, hi=higher, namely=config["connectives"]["namely"])
    return templates["cot_direct"].format(hi=higher, lo=lower)


def render_chain(order: Sequence[str]) -> str:
    """The assembled total order as a terse symbolic chain.

    Args:
        order: The true order, greatest first.

    Returns:
        e.g. ``"राम > श्याम > मोहन"``.
    """
    return " > ".join(order)


def join_sentences(segments: Sequence[str]) -> str:
    """Join clause segments into a sentence sequence terminated by dandas.

    Templates carry no terminal punctuation, so the joiner owns it entirely and
    cannot double it up.

    Args:
        segments: Clauses, none ending in a danda.

    Returns:
        The joined string, ending in a danda.
    """
    return (DANDA + " ").join(segments) + DANDA


