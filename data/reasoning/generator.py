def load_language_config(path: Path) -> dict:
    """Load one language's surface configuration.

    Relative paths inside the config (name pools) are resolved against the
    config file's own directory, so the generator can be run from anywhere.

    Args:
        path: Path to ``configs/hi.yaml`` / ``configs/hi_perf.yaml``.

    Returns:
        The parsed config with ``names.train`` / ``names.test`` rewritten to
        absolute paths.
    """
    path = Path(path)
    config = yaml.safe_load(path.read_text(encoding="utf-8"))
    for key in ("train", "test"):
        config["names"][key] = (path.parent / config["names"][key]).resolve()
    return config


def load_build_config(path: Path) -> dict:
    """Load the shared build plan (sizes, mixtures, slice definitions).

    Args:
        path: Path to ``configs/build.yaml``.

    Returns:
        The parsed build plan.
    """
    return yaml.safe_load(Path(path).read_text(encoding="utf-8"))


def load_names(path: Path) -> list[str]:
    """Read a name pool file.

    Format is ``<name>\\t<gender>`` per line; ``#`` comments and blank lines
    are skipped.  Use :func:`load_name_pool` when the gender tag is needed --
    predicate adjectives agree with it (revision Fix B).

    Args:
        path: Path to a ``*_names_*.txt`` pool.

    Returns:
        The names in file order.

    Raises:
        ValueError: If the pool contains a duplicate name, which would let one
            problem draw the same entity twice.
    """
    return [name for name, _ in load_name_pool(path)]


def load_name_pool(path: Path) -> list[tuple[str, str]]:
    """Read a name pool as ``(name, gender)`` pairs.

    Args:
        path: Path to a ``*_names_*.txt`` pool.

    Returns:
        The entries in file order; a missing tag defaults to ``"m"``.

    Raises:
        ValueError: If the pool contains a duplicate name, which would let one
            problem draw the same entity twice.
    """
    entries: list[tuple[str, str]] = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        entries.append((parts[0], parts[1] if len(parts) > 1 else "m"))
    names = [name for name, _ in entries]
    duplicates = {n for n in names if names.count(n) > 1}
    if duplicates:
        raise ValueError(f"{path}: duplicate names {sorted(duplicates)}")
    return entries


def load_name_genders(path: Path) -> dict[str, str]:
    """Map each name in a pool to its gender tag.

    Args:
        path: Path to a ``*_names_*.txt`` pool.

    Returns:
        Name to ``"m"`` or ``"f"``.
    """
    return dict(load_name_pool(path))


def resolve_templates(config: dict, domain: dict) -> dict:
    """Language templates with this domain's overrides applied.

    Domains override templates rather than the generator special-casing them.
    The wealth domain is why: it is phrased with possession (``X के पास N रुपये
    हैं``, ``Xसँग N रुपैयाँ छ``) instead of the ``X की <attr>`` construction
    every other domain uses, and Hindi wealth also needs the ``ज़्यादा``
    intensifier.  Expressing that as config data keeps generator.py free of
    per-domain branches.

    Args:
        config: Language config.
        domain: The chosen domain's block.

    Returns:
        The effective template map for this domain.
    """
    return {**config["templates"], **domain.get("templates", {})}


def adjective(domain: dict, direction: str, gender: str) -> str:
    """The comparison adjective, inflected for the subject's gender.

    Args:
        domain: The chosen domain's block.
        direction: ``"more"`` or ``"less"``.
        gender: ``"m"`` or ``"f"``.

    Returns:
        The surface adjective.  Invariant adjectives store the same string
        under both keys, so no caller needs to know which are which.
    """
    forms = domain[direction]
    return forms.get(gender, forms["m"])


def gender_of(genders: dict[str, str], name: str) -> str:
    """Gender tag for one name, defaulting to masculine.

    Args:
        genders: Name to gender, from :func:`load_name_genders`.
        name: The entity name.

    Returns:
        ``"m"`` or ``"f"``.
    """
    return genders.get(name, "m")


