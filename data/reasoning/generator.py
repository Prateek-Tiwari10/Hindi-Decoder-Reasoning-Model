# Question construction
#
# Each builder returns (question_sentence, query_metadata, answer).  The
# metadata is what lets the independent solver in checks.py re-derive the
# answer from `premises` alone, and what Part 3 needs to score chain validity.
# ---------------------------------------------------------------------------


def build_extremum_question(rng: random.Random, config: dict, domain: dict,
                            order: Sequence[str]) -> tuple[str, dict, str]:
    """"Who is the most / least X?" -- requires resolving the whole chain.

    The end is drawn with p = 0.5 so the answer is the first element of the
    true order half the time and the last element the other half; a model that
    always guesses "the first entity mentioned" gets no edge.

    Args:
        rng: Seeded generator.
        config: Language config.
        domain: The chosen domain's block.
        order: The true order, greatest first.

    Returns:
        ``(question, query_metadata, answer)``.
    """
    templates = resolve_templates(config, domain)
    want_max = rng.random() < 0.5
    # MASCULINE, whatever the answer's gender.  The referent is the
    # interrogative (कौन / को), which is grammatically masculine -- and
    # agreeing it with the answer instead would leak the answer's gender into
    # the prompt and halve the candidate set for free.
    adjective_form = adjective(domain, "more" if want_max else "less", "m")
    question = templates["q_extremum"].format(adj=adjective_form)
    answer = order[0] if want_max else order[-1]
    query = {"kind": "extremum", "end": "max" if want_max else "min"}
    return question, query, answer


def build_pairwise_question(rng: random.Random, config: dict, domain: dict,
                            order: Sequence[str], pair: tuple[int, int],
                            genders: dict[str, str]) -> tuple[str, dict, str]:
    """"Is A more X than C?" for a pair that was never stated as a premise.

    This is the sharpest transitivity probe in the set, so two independent
    coins keep it from being answerable by position or by keyword:

    * ``swap`` decides which of the two entities is named first, so the
      first-named entity is not systematically the greater one;
    * ``ask_more`` decides whether the question uses the greater or the lesser
      adjective, which flips the correct yes/no answer.

    The second coin alone makes the label exactly 50/50 whatever the pair is,
    which is why no post-hoc balancing of the answer distribution is needed.

    Args:
        rng: Seeded generator.
        config: Language config.
        domain: The chosen domain's block.
        order: The true order, greatest first.
        pair: ``(higher_index, lower_index)``, non-consecutive and reserved out
            of the premise set by :func:`select_premise_edges`.
        genders: Name to gender, for adjective agreement.

    Returns:
        ``(question, query_metadata, answer)`` where the answer is the
        language's yes or no label.
    """
    templates = resolve_templates(config, domain)
    higher_index, lower_index = pair
    swap = rng.random() < 0.5
    first, second = ((order[lower_index], order[higher_index]) if swap
                     else (order[higher_index], order[lower_index]))

    ask_more = rng.random() < 0.5
    # The subject is the first-named entity, so the adjective takes its gender.
    adjective_form = adjective(domain, "more" if ask_more else "less",
                               gender_of(genders, first))
    question = templates["q_pairwise"].format(
        a=first, b=second, adj=adjective_form)

    first_is_greater = order.index(first) < order.index(second)
    affirmative = first_is_greater if ask_more else not first_is_greater
    answer = config["labels"]["affirmative" if affirmative else "negative"]

    query = {"kind": "pairwise", "a": first, "b": second,
             "direction": "more" if ask_more else "less"}
    return question, query, answer


def build_ordering_question(config: dict, domain: dict,
                            order: Sequence[str]) -> tuple[str, dict, str]:
    """"Put them all in descending order of X."

    The question names the attribute and the direction explicitly.  "Put them
    in order" alone would be ambiguous about which end comes first, and an
    ambiguous prompt cannot have an exact-match answer.

    Args:
        config: Language config.
        domain: The chosen domain's block.
        order: The true order, greatest first.

    Returns:
        ``(question, query_metadata, answer)`` where the answer is the full
        chain rendered as ``A > B > C``.
    """
    question = resolve_templates(config, domain)["q_ordering"].format(
        attr=domain["attr"], poss=domain["possessive"])
    return question, {"kind": "ordering"}, render_chain(order)


def choose_bound_query(rng: random.Random, depth: int, anchor_index: int,
                       edges: Sequence[tuple[int, int]], min_depth: int
                       ) -> tuple[int, bool]:
    """Pick which entity a numeric bound question asks about.

    From ``min_depth`` up, the queried entity must not be directly linked to
    the anchor by a stated premise.  Otherwise "is X above 170?" collapses to a
    single hop off the anchor and stops testing propagation along the chain.

    Args:
        rng: Seeded generator.
        depth: Number of entities.
        anchor_index: Position of the entity whose value is revealed.
        edges: The stated premise edges.
        min_depth: Depth from which the non-adjacency rule applies.

    Returns:
        ``(query_index, relaxed)``.  ``relaxed`` is True if no non-adjacent
        candidate existed and the rule had to be dropped for this problem;
        run.py counts those so the fallback rate is reported rather than
        hidden.
    """
    others = [i for i in range(depth) if i != anchor_index]
    if depth < min_depth:
        return rng.choice(others), False

    stated = {frozenset(edge) for edge in edges}
    candidates = [i for i in others
                  if frozenset((anchor_index, i)) not in stated]
    if not candidates:
        return rng.choice(others), True
    return rng.choice(candidates), False


def build_bound_question(rng: random.Random, config: dict, domain: dict,
                         order: Sequence[str], values: Sequence[int],
                         anchor_index: int, query_index: int
                         ) -> tuple[str, dict, str]:
    """"Is A's height more than 170 cm?" -- the numeric variant of pairwise.

    The answer is a BOUND, never a value: the model is told exactly one
    entity's number and must propagate the inequality along the chain to place
    a second entity relative to it.  Revealing a second value would turn the
    problem into arithmetic and remove the chaining entirely (§5).

    As with the relational pairwise question, the comparison direction is a
    fair coin, so the yes/no label is balanced by construction.

    Args:
        rng: Seeded generator.
        config: Language config.
        domain: The chosen domain's block.
        order: The true order, greatest first.
        values: Attribute values aligned with ``order``, descending.
        anchor_index: The entity whose value is revealed.
        query_index: The entity the question asks about.

    Returns:
        ``(question, query_metadata, answer)``.
    """
    ask_more = rng.random() < 0.5
    bound_word = config["bounds"]["more" if ask_more else "less"]
    value = values[anchor_index]
    question = resolve_templates(config, domain)["q_bound"].format(
        e=order[query_index], poss=domain["possessive"], attr=domain["attr"],
        v=value, unit=domain["unit"], bound=bound_word)

    # Position 0 is the greatest, so a SMALLER index means a LARGER value.
    query_is_greater = query_index < anchor_index
    affirmative = query_is_greater if ask_more else not query_is_greater
    answer = config["labels"]["affirmative" if affirmative else "negative"]

    query = {"kind": "bound", "entity": order[query_index],
             "anchor": order[anchor_index], "value": value,
             "unit": domain["unit"], "direction": "more" if ask_more else "less"}
    return question, query, answer


