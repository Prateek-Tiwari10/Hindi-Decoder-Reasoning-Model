def derive_seed(master_seed: int, slice_tag: str, index: int,
                attempt: int = 0) -> int:
    """Seed for one record, derived from its address in the build.

    Deterministic in ``(master_seed, slice_tag, index, attempt)`` and nothing
    else, so a record does not depend on how many records preceded it.  The
    ``attempt`` term gives rejection resampling a fresh stream without
    disturbing any other record's stream.

    Args:
        master_seed: The build plan's seed.
        slice_tag: Which slice this record belongs to.
        index: Position within the slice.
        attempt: Resample attempt number.

    Returns:
        A seed for :class:`random.Random`.
    """
    tag = sum((ord(c) * (i + 1) for i, c in enumerate(slice_tag)), 0)
    return (master_seed * 1_000_003 + tag * 10_007 + index * 31 + attempt) % (2 ** 63)


def build_record(config: dict, build_config: dict, spec: dict, slice_tag: str,
                 pool: Sequence[str], genders: dict[str, str], index: int,
                 seed: int) -> dict:
    """Generate one complete record.

    The order of operations is load-bearing.  The queried pair for a pairwise
    question is chosen BEFORE the premise set, so it can be reserved out of it;
    choosing them the other way round would mean either discarding problems
    whose only non-consecutive pair had already been stated, or silently
    letting the queried pair be a given premise and quietly turning the
    sharpest transitivity probe into a lookup.

    Args:
        config: Language config.
        build_config: The build plan.
        spec: This slice's definition.
        slice_tag: The slice's name.
        pool: Names available to this slice (train pool or test pool).
        genders: Name to gender for that pool, for adjective agreement.
        index: Position within the slice.
        seed: This record's derived seed.

    Returns:
        The record dict, matching the §3 schema plus two documented additions:
        ``question_variant`` (``"relation"`` or ``"bound"``) and ``query``
        (what the question asked, needed by the independent solver and by
        Part 3's chain scoring).

    Raises:
        RuntimeError: If the uniqueness gate rejects the constructed premise
            set, which would mean the construction itself is broken.
    """
    rng = random.Random(seed)

    family = weighted_choice(rng, spec["families"])
    depth = rng.choice(spec["depths"])
    domain_names = (build_config["core_domains"] if spec["domains"] == "core"
                    else spec["domains"])
    domain_name = rng.choice(sorted(domain_names))
    domain = config["domains"][domain_name]
    question_type = choose_question_type(rng, family, depth, build_config)

    order = sample_true_order(rng, pool, depth)

    # Reserve the queried pair before the premises are chosen (see docstring).
    reserved = None
    if question_type == "pairwise":
        reserved = rng.choice(nonconsecutive_pairs(depth))

    edges = select_premise_edges(rng, depth, build_config, reserved)
    if not uniquely_determines_total_order(depth, edges):
        raise RuntimeError(
            f"uniqueness gate rejected a constructed problem: depth={depth} "
            f"edges={edges}; the construction in select_premise_edges is wrong")
    premises = apply_polarity(rng, edges)

    # Numeric and mixed families reveal exactly one entity's value.
    anchor = None
    values = None
    relaxed_bound = False
    if family in ("numeric", "mixed"):
        low, high = domain["range"]
        values = assign_values(rng, depth, low, high)
        anchor_index = rng.randrange(depth)
        anchor = {"entity": order[anchor_index], "value": values[anchor_index],
                  "unit": domain["unit"]}

    if question_type == "extremum":
        question, query, answer = build_extremum_question(
            rng, config, domain, order)
    elif question_type == "pairwise":
        question, query, answer = build_pairwise_question(
            rng, config, domain, order, reserved, genders)
    elif question_type == "ordering":
        question, query, answer = build_ordering_question(config, domain, order)
    elif question_type == "bound":
        query_index, relaxed_bound = choose_bound_query(
            rng, depth, anchor_index, edges,
            build_config["bound_nonadjacent_min_depth"])
        question, query, answer = build_bound_question(
            rng, config, domain, order, values, anchor_index, query_index)
    else:
        raise ValueError(f"unknown question type {question_type!r}")

    premise_sentences = [render_premise(config, domain, order, p, genders)
                         for p in premises]
    if anchor is not None:
        # The anchor is stated first, as in the §7 numeric illustration.
        premise_sentences.insert(
            0, resolve_templates(config, domain)["anchor"].format(
                e=anchor["entity"], poss=domain["possessive"],
                attr=domain["attr"], v=anchor["value"], unit=domain["unit"]))

    prompt = build_prompt(config, premise_sentences, question)
    completion = build_completion(config, domain, order, premises, query,
                                  answer, anchor, genders)

    # question_type stays inside the three values declared by the §3 schema;
    # the bound variant is recorded alongside it rather than as a fourth value.
    schema_question_type = "pairwise" if question_type == "bound" else question_type

    return {
        "id": f"{config['code']}-{FAMILY_ABBREV[family]}-{index:06d}",
        "language": config["code"],
        "task_family": family,
        "domain": domain_name,
        "question_type": schema_question_type,
        "question_variant": "bound" if question_type == "bound" else "relation",
        "depth": depth,
        "prompt": prompt,
        "completion": completion,
        "answer": answer,
        "true_order": list(order),
        "premises": [render_premise_record(order, p) for p in premises],
        "numeric_anchor": anchor,
        "query": query,
        "split": spec["split"],
        "slice": slice_tag,
        "seed": seed,
        "n_nonconsecutive_premises": sum(1 for p in premises if not p.consecutive),
        "bound_adjacency_relaxed": relaxed_bound,
    }


def generate_slice(config: dict, build_config: dict, slice_tag: str,
                   seen_prompts: dict[str, str]) -> tuple[list[dict], dict]:
    """Generate every record in one slice, rejecting duplicate prompts.

    ``seen_prompts`` is shared across every slice of a language, so a prompt
    can never appear in two splits -- the §8 requirement that makes the test
    slices honest.  A collision is resolved by resampling that record with a
    fresh derived seed rather than by dropping it, so the slice still lands on
    its configured size.

    Args:
        config: Language config.
        build_config: The build plan.
        slice_tag: Which slice to build.
        seen_prompts: Prompt to slice tag, mutated in place.

    Returns:
        ``(records, stats)`` where stats reports collisions and the
        non-consecutive premise coverage that check G4 reads.

    Raises:
        RuntimeError: If a record cannot find an unused prompt within the
            configured attempt budget, which means the name pool or the
            template variety is too small for the requested slice size.
    """
    spec = build_config["slices"][slice_tag]
    pool_entries = load_name_pool(config["names"][spec["pool"]])
    pool_names = [name for name, _ in pool_entries]
    pool_genders = dict(pool_entries)
    max_attempts = build_config["max_resample_attempts"]

    records: list[dict] = []
    collisions = 0
    for index in range(spec["size"]):
        for attempt in range(max_attempts):
            seed = derive_seed(build_config["seed"], slice_tag, index, attempt)
            record = build_record(config, build_config, spec, slice_tag,
                                  pool_names, pool_genders, index, seed)
            if record["prompt"] not in seen_prompts:
                break
            collisions += 1
        else:
            raise RuntimeError(
                f"{slice_tag}[{index}]: no unique prompt in {max_attempts} "
                f"attempts; the name pool or template variety is too small "
                f"for size={spec['size']}")
        seen_prompts[record["prompt"]] = slice_tag
        records.append(record)

    deep = [r for r in records
            if r["depth"] >= build_config["nonconsecutive"]["min_depth"]]
    deep_eligible = [r for r in deep
                     if not (r["question_type"] == "pairwise"
                             and r["question_variant"] == "relation"
                             and r["depth"] == 3)]
    stats = {
        "size": len(records),
        "prompt_collisions_resampled": collisions,
        "depth_ge_min": len(deep),
        "depth_ge_min_with_nonconsecutive": sum(
            1 for r in deep if r["n_nonconsecutive_premises"] > 0),
        "depth_ge_min_eligible": len(deep_eligible),
        "depth_ge_min_eligible_with_nonconsecutive": sum(
            1 for r in deep_eligible if r["n_nonconsecutive_premises"] > 0),
        "bound_adjacency_relaxed": sum(
            1 for r in records if r["bound_adjacency_relaxed"]),
    }
    return records, stats
